export type Lang = "fi" | "en";
const catalogs: Record<Lang, Catalog> = { fi, en };

let current: Lang = "fi";

export function setLang(lang: Lang): void {
  current = lang;
}

export function getLang(): Lang {
  return current;
}

export function t(key: TextKey): string {
  return catalogs[current][key];
}

/** fmt() with the singular key when n is 1 (Finnish: "1 käsiteltävä", "2 käsiteltävää"). */
export function plural(n: number, one: TextKey, many: TextKey, values: Record<string, string | number> = {}): string {
  return fmt(n === 1 ? one : many, { n, ...values });
}

/** A catalog text with {name} placeholders filled. */
export function fmt(key: TextKey, values: Record<string, string | number>): string {
  return t(key).replace(/\{(\w+)\}/g, (m, k: string) => (k in values ? String(values[k]) : m));
}

/** Locale for number and date formatting in the current language. */
export function locale(): string {
  return current === "fi" ? "fi-FI" : "en-GB";
}
